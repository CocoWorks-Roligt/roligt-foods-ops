#!/usr/bin/env node
/** Emits api/_lib/baseSchema.ts from every synced base's topup state — one entry
 *  per topup-state.<base8>.json, so the repo carries all bases at once and the
 *  active one is chosen by ZOHO_BASE_ID at import (the default being whatever
 *  this checkout's .env names at generation time). Regeneration also happens
 *  automatically after scripts/zoho/topup.mjs syncs a base. */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = dirname(fileURLToPath(import.meta.url))
const CW = join(ROOT, '..', '..')

// every per-base state file; each must record which base it belongs to
const states = []
for (const f of readdirSync(ROOT).filter((n) => /^topup-state\.\w+\.json$/.test(n)).sort()) {
  const st = JSON.parse(readFileSync(join(ROOT, f), 'utf8'))
  if (!st.base) { console.error(`${f} records no "base" — re-sync that base to rewrite its state`); process.exit(1) }
  states.push({ file: f, base: st.base, tables: st.tables })
}
const byBase = new Map()
for (const s of states) {
  if (byBase.has(s.base)) { console.error(`two state files claim base ${s.base}: ${byBase.get(s.base).file} and ${s.file}`); process.exit(1) }
  byBase.set(s.base, s)
}
if (!states.length) { console.error('no topup-state.*.json found — sync a base first (scripts/zoho/topup.mjs <base-id>)'); process.exit(1) }

// the default is the base this checkout develops against: .env's ZOHO_BASE_ID
// (what the dev server and the BFF read), falling back to the shell's, and it
// must be a base that was actually synced
const dotEnv = existsRead(join(CW, '.env'))
const DEFAULT = process.env.ZOHO_BASE_ID || (dotEnv && dotEnv.ZOHO_BASE_ID) || ''
if (!DEFAULT) { console.error('set ZOHO_BASE_ID (or put it in .env) so the generated schema knows its default base'); process.exit(1) }
if (!byBase.has(DEFAULT)) {
  console.error(`default base ${DEFAULT} has no state file (have: ${states.map((s) => s.base).join(', ')}) — sync it first`)
  process.exit(1)
}

// supabase table name → base table name (the 22 collections + ledger + audits)
const TABLE_FOR = {
  vendor_types: 'Vendor Types', vendors: 'Vendors', customers: 'Customers',
  purchase_products: 'Purchase Products', storage_locations: 'Storage Locations',
  items: 'Items', products: 'Products', melanges: 'Melanges', grns: 'GRNs',
  batches: 'Batches', packing_runs: 'Packing Runs', orders: 'Orders',
  order_lines: 'Order Lines', qcs: 'QC Records', dispatches: 'Dispatches',
  stock_issues: 'Stock Issues', lab_reports: 'Lab Reports',
  test_parameters: 'Test Parameters', sticker_templates: 'Sticker Templates',
  sticker_prints: 'Sticker Prints', staff: 'Staff', shifts: 'Shifts',
  attendance: 'Attendance', production_plans: 'Production Plans',
  ledger: 'Ledger', audits: 'Audit Log',
}

const baseEntry = (s) => {
  const rows = Object.entries(s.tables)
    .map(([name, t]) => `    ${JSON.stringify(name)}: ${JSON.stringify({ name, id: t.id, appId: t.appId, ...(t.dataJson ? { dataJson: t.dataJson } : {}), fields: t.fields })},`)
    .join('\n')
  return `  // synced from ${s.file}\n  ${JSON.stringify(s.base)}: {\n${rows}\n  },`
}

const out = `// GENERATED by scripts/zoho/gen-base-schema.mjs — do not edit by hand.
// One entry per synced base; the active one is chosen by ZOHO_BASE_ID at import
// (DEFAULT_BASE_ID when unset), and a base nobody synced refuses to load — the
// multi-base answer to a half-done switch: local scratch and production deploy
// from the same committed file, and a mis-set ZOHO_BASE_ID fails at boot.
export interface TableRef {
  name: string
  id: string
  appId: string
  dataJson?: string
  fields: Record<string, string>
}

export const SCHEMAS: Record<string, Record<string, TableRef>> = {
${states.map(baseEntry).join('\n')}
}

export const DEFAULT_BASE_ID = ${JSON.stringify(DEFAULT)}

export const TABLE_FOR: Record<string, string> = ${JSON.stringify(TABLE_FOR, null, 2)}

/**
 * The tables of the named base. Unset falls back to DEFAULT_BASE_ID — the base
 * this checkout was generated against, and the world tests run in; a base with
 * no synced state throws rather than guess, naming what to run.
 */
export function schemaFor(baseId?: string | undefined): Record<string, TableRef> {
  const id = baseId || DEFAULT_BASE_ID
  const tables = SCHEMAS[id]
  if (!tables) {
    throw new Error(
      'no generated schema for base ' + id + ' (have: ' + Object.keys(SCHEMAS).join(', ') + ')' +
        ' — sync it first (node scripts/zoho/topup.mjs ' + id + '), which regenerates this file',
    )
  }
  return tables
}

export const T = schemaFor(process.env.ZOHO_BASE_ID)
`
writeFileSync(join(ROOT, '..', '..', 'api', '_lib', 'baseSchema.ts'), out)
console.log('wrote api/_lib/baseSchema.ts with', states.length, 'base(s):', states.map((s) => s.base).join(', '), '— default', DEFAULT)

function existsRead(f) {
  try {
    return Object.fromEntries(
      readFileSync(f, 'utf8').split('\n')
        .filter((l) => l.includes('=') && !l.startsWith('#'))
        .map((l) => [l.slice(0, l.indexOf('=')).trim(), l.slice(l.indexOf('=') + 1).trim()]),
    )
  } catch { return null }
}
